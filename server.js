/**
 * SkillBridge RPL - AI Chatbot Backend Server (Node.js)
 * 
 * Standalone, zero-dependency Node.js HTTP server.
 * Proxies chat requests to Google Gemini or OpenAI APIs securely.
 * API keys are loaded from .env and NEVER exposed to frontend clients.
 */

const http = require('http');
const https = require('https');
const fs = require('fs');
const path = require('path');

// 1. Load .env file manually without external dependencies
function loadEnv() {
  const envPath = path.join(__dirname, '.env');
  if (fs.existsSync(envPath)) {
    const content = fs.readFileSync(envPath, 'utf8');
    content.split(/\r?\n/).forEach(line => {
      const trimmed = line.trim();
      if (trimmed && !trimmed.startsWith('#') && trimmed.includes('=')) {
        const idx = trimmed.indexOf('=');
        const key = trimmed.substring(0, idx).trim();
        let val = trimmed.substring(idx + 1).trim();
        // Remove surrounding quotes if present
        if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
          val = val.substring(1, val.length - 1);
        }
        if (!process.env[key]) {
          process.env[key] = val;
        }
      }
    });
  }
}

loadEnv();

const PORT = process.env.PORT || 3000;
const GEMINI_API_KEY = process.env.GEMINI_API_KEY || process.env.GOOGLE_API_KEY || '';
const OPENAI_API_KEY = process.env.OPENAI_API_KEY || '';

const DEFAULT_SYSTEM_PROMPT = process.env.SYSTEM_PROMPT || 
  "You are the SkillBridge RPL AI Academic Advisor, an expert on Recognition of Prior Learning (RPL), vocational education, portfolio evidence, and skill gap bridging. You help students and career switchers convert real-world experience into recognized qualifications. Keep responses encouraging, well-structured, concise, and academically sound.";

// Helper: send JSON with CORS headers
function sendJson(res, statusCode, data) {
  const body = JSON.stringify(data);
  res.writeHead(statusCode, {
    'Content-Type': 'application/json',
    'Access-Control-Allow-Origin': '*',
    'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
    'Access-Control-Allow-Headers': 'Content-Type, Authorization'
  });
  res.end(body);
}

// 2. Call Google Gemini API
async function callGemini(message, history) {
  const url = `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${GEMINI_API_KEY}`;
  
  // Build contents payload
  const contents = [];
  
  // Add history
  if (Array.isArray(history)) {
    history.slice(-4).forEach(h => {
      contents.push({
        role: h.role === 'assistant' ? 'model' : 'user',
        parts: [{ text: h.content }]
      });
    });
  }
  
  // Current user message with system guidance
  contents.push({
    role: 'user',
    parts: [{ text: `[System Instruction: ${DEFAULT_SYSTEM_PROMPT}]\n\nCandidate Question: ${message}` }]
  });

  const payload = JSON.stringify({
    contents: contents,
    generationConfig: {
      temperature: 0.7,
      maxOutputTokens: 800
    }
  });

  return new Promise((resolve, reject) => {
    const req = https.request(url, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Content-Length': Buffer.byteLength(payload)
      }
    }, (res) => {
      let raw = '';
      res.on('data', chunk => raw += chunk);
      res.on('end', () => {
        try {
          const json = JSON.parse(raw);
          if (res.statusCode >= 200 && res.statusCode < 300) {
            const reply = json.candidates?.[0]?.content?.parts?.[0]?.text;
            if (reply) {
              resolve(reply);
            } else {
              reject(new Error('No response content generated by Gemini.'));
            }
          } else {
            const errDetail = json.error?.message || `Gemini API error (Status ${res.statusCode})`;
            reject(new Error(errDetail));
          }
        } catch (e) {
          reject(new Error(`Failed to parse Gemini response: ${raw}`));
        }
      });
    });

    req.on('error', reject);
    req.write(payload);
    req.end();
  });
}

// 3. Call OpenAI API
async function callOpenAI(message, history) {
  const url = 'https://api.openai.com/v1/chat/completions';
  
  const messages = [
    { role: 'system', content: DEFAULT_SYSTEM_PROMPT }
  ];

  if (Array.isArray(history)) {
    history.slice(-4).forEach(h => {
      messages.push({
        role: h.role === 'assistant' ? 'assistant' : 'user',
        content: h.content
      });
    });
  }

  messages.push({ role: 'user', content: message });

  const payload = JSON.stringify({
    model: 'gpt-4o-mini',
    messages: messages,
    temperature: 0.7,
    max_tokens: 800
  });

  return new Promise((resolve, reject) => {
    const req = https.request(url, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Authorization': `Bearer ${OPENAI_API_KEY}`,
        'Content-Length': Buffer.byteLength(payload)
      }
    }, (res) => {
      let raw = '';
      res.on('data', chunk => raw += chunk);
      res.on('end', () => {
        try {
          const json = JSON.parse(raw);
          if (res.statusCode >= 200 && res.statusCode < 300) {
            const reply = json.choices?.[0]?.message?.content;
            if (reply) {
              resolve(reply);
            } else {
              reject(new Error('No response content returned by OpenAI.'));
            }
          } else {
            const errDetail = json.error?.message || `OpenAI API error (Status ${res.statusCode})`;
            reject(new Error(errDetail));
          }
        } catch (e) {
          reject(new Error(`Failed to parse OpenAI response: ${raw}`));
        }
      });
    });

    req.on('error', reject);
    req.write(payload);
    req.end();
  });
}

// 4. Create HTTP Server
const server = http.createServer(async (req, res) => {
  // Handle CORS preflight
  if (req.method === 'OPTIONS') {
    res.writeHead(204, {
      'Access-Control-Allow-Origin': '*',
      'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
      'Access-Control-Allow-Headers': 'Content-Type, Authorization'
    });
    return res.end();
  }

  const parsedUrl = new URL(req.url, `http://${req.headers.host || 'localhost'}`);
  const pathname = parsedUrl.pathname;

  // Endpoint: Health & Configuration Status Check
  if (req.method === 'GET' && (pathname === '/api/status' || pathname === '/status')) {
    const isConfigured = Boolean(GEMINI_API_KEY && GEMINI_API_KEY.length > 5) || 
                         Boolean(OPENAI_API_KEY && OPENAI_API_KEY.length > 5);

    return sendJson(res, 200, {
      status: 'online',
      service: 'SkillBridge RPL AI Proxy',
      configured: isConfigured,
      activeProvider: GEMINI_API_KEY ? 'Google Gemini' : (OPENAI_API_KEY ? 'OpenAI' : 'None'),
      notice: isConfigured 
        ? 'AI backend is configured and ready to process requests.' 
        : 'AI API key is missing. Please set GEMINI_API_KEY or OPENAI_API_KEY in server/.env.'
    });
  }

  // Endpoint: Chat completions
  if (req.method === 'POST' && (pathname === '/api/chat' || pathname === '/chat')) {
    let body = '';
    req.on('data', chunk => body += chunk);
    req.on('end', async () => {
      try {
        const payload = JSON.parse(body || '{}');
        const userMessage = payload.message?.trim();
        const history = payload.history || [];

        if (!userMessage) {
          return sendJson(res, 400, { error: 'A message field is required in the request body.' });
        }

        // Check if any key is configured
        if (!GEMINI_API_KEY && !OPENAI_API_KEY) {
          return sendJson(res, 503, {
            error: 'AI assistant is not configured. Please add GEMINI_API_KEY or OPENAI_API_KEY to server/.env to enable genuine AI responses.',
            configured: false
          });
        }

        let reply = '';
        if (GEMINI_API_KEY) {
          reply = await callGemini(userMessage, history);
        } else if (OPENAI_API_KEY) {
          reply = await callOpenAI(userMessage, history);
        }

        return sendJson(res, 200, {
          reply: reply,
          provider: GEMINI_API_KEY ? 'Google Gemini' : 'OpenAI',
          timestamp: new Date().toISOString()
        });

      } catch (err) {
        console.error('Chat processing error:', err.message);
        return sendJson(res, 500, {
          error: `AI processing failed: ${err.message}`
        });
      }
    });
    return;
  }

  // Fallback 404
  sendJson(res, 404, { error: 'Endpoint not found. Use POST /api/chat or GET /api/status.' });
});

server.listen(PORT, () => {
  console.log(`=======================================================`);
  console.log(` SkillBridge RPL - AI Backend Server`);
  console.log(` Listening on: http://localhost:${PORT}`);
  console.log(` Endpoints:`);
  console.log(`   - GET  http://localhost:${PORT}/api/status`);
  console.log(`   - POST http://localhost:${PORT}/api/chat`);
  console.log(` AI Provider: ${GEMINI_API_KEY ? 'Google Gemini' : (OPENAI_API_KEY ? 'OpenAI' : 'None (Setup required in server/.env)')}`);
  console.log(`=======================================================`);
});
